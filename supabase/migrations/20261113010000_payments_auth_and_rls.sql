create extension if not exists pgcrypto with schema extensions;

create table if not exists public.payments (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete set null,
    reference uuid not null default gen_random_uuid() unique,
    product_name text not null,
    unit_amount bigint not null,
    quantity smallint not null,
    amount_total bigint not null,
    currency varchar(3) not null,
    status varchar(24) not null default 'pending',
    stripe_checkout_session_id text unique,
    stripe_payment_intent_id text unique,
    customer_email text,
    paid_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.payments
    add column if not exists user_id uuid references auth.users(id) on delete set null;

alter table public.payments
    alter column reference set default gen_random_uuid(),
    alter column status set default 'pending',
    alter column created_at set default now(),
    alter column updated_at set default now();

do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conname = 'payments_positive_amounts'
          and conrelid = 'public.payments'::regclass
    ) then
        alter table public.payments
            add constraint payments_positive_amounts
            check (unit_amount > 0 and quantity > 0 and amount_total > 0);
    end if;

    if not exists (
        select 1
        from pg_constraint
        where conname = 'payments_valid_status'
          and conrelid = 'public.payments'::regclass
    ) then
        alter table public.payments
            add constraint payments_valid_status
            check (status in ('pending', 'processing', 'paid', 'failed', 'expired'));
    end if;
end
$$;

create index if not exists payments_user_created_at_index
    on public.payments (user_id, created_at desc);
create index if not exists payments_status_index
    on public.payments (status);

create table if not exists public.stripe_webhook_events (
    id bigint generated by default as identity primary key,
    event_id text not null unique,
    type text not null,
    processed_at timestamptz not null default now(),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.stripe_webhook_events
    alter column processed_at set default now(),
    alter column created_at set default now(),
    alter column updated_at set default now();

alter table public.payments enable row level security;
alter table public.stripe_webhook_events enable row level security;

drop policy if exists "Users can read their own payments" on public.payments;
create policy "Users can read their own payments"
    on public.payments
    for select
    to authenticated
    using ((select auth.uid()) = user_id);

create or replace function public.process_stripe_webhook(
    p_event_id text,
    p_event_type text,
    p_session_id text,
    p_payment_status text,
    p_payment_intent_id text,
    p_customer_email text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
    inserted_count integer;
    next_status text;
begin
    insert into public.stripe_webhook_events (
        event_id,
        type,
        processed_at,
        created_at,
        updated_at
    )
    values (p_event_id, p_event_type, now(), now(), now())
    on conflict (event_id) do nothing;

    get diagnostics inserted_count = row_count;

    if inserted_count = 0 then
        return false;
    end if;

    next_status := case
        when p_event_type = 'checkout.session.async_payment_failed' then 'failed'
        when p_event_type = 'checkout.session.expired' then 'expired'
        when p_event_type = 'checkout.session.async_payment_succeeded' then 'paid'
        when p_event_type = 'checkout.session.completed' and p_payment_status = 'paid' then 'paid'
        when p_event_type = 'checkout.session.completed' then 'processing'
        else null
    end;

    if next_status is null or p_session_id is null then
        return true;
    end if;

    update public.payments
    set
        status = next_status,
        stripe_payment_intent_id = coalesce(
            p_payment_intent_id,
            stripe_payment_intent_id
        ),
        customer_email = coalesce(p_customer_email, customer_email),
        paid_at = case
            when next_status = 'paid' then coalesce(paid_at, now())
            else paid_at
        end,
        updated_at = now()
    where stripe_checkout_session_id = p_session_id;

    if not found then
        raise exception 'Payment for Stripe Checkout Session % was not found.', p_session_id;
    end if;

    return true;
end;
$$;

revoke all on function public.process_stripe_webhook(
    text,
    text,
    text,
    text,
    text,
    text
) from public, anon, authenticated;

grant execute on function public.process_stripe_webhook(
    text,
    text,
    text,
    text,
    text,
    text
) to service_role;

revoke all on table public.payments from anon, authenticated;
grant select on table public.payments to authenticated;
grant all on table public.payments to service_role;

revoke all on table public.stripe_webhook_events from anon, authenticated;
grant all on table public.stripe_webhook_events to service_role;

grant usage, select on sequence public.payments_id_seq to service_role;
grant usage, select on sequence public.stripe_webhook_events_id_seq to service_role;
