create or replace function public.process_stripe_webhook(
    p_event_id text,
    p_event_type text,
    p_session_id text,
    p_payment_status text,
    p_payment_intent_id text,
    p_customer_email text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
    inserted_count integer;
    next_payment_status text;
    next_request_status text;
    linked_request_id uuid;
begin
    insert into public.stripe_webhook_events (
        event_id,
        type,
        processed_at,
        created_at,
        updated_at
    ) values (p_event_id, p_event_type, now(), now(), now())
    on conflict (event_id) do nothing;

    get diagnostics inserted_count = row_count;

    if inserted_count = 0 then
        perform public.resolve_stripe_webhook_failure(p_event_id, 'duplicate_already_processed');
        return false;
    end if;

    next_payment_status := case
        when p_event_type = 'checkout.session.async_payment_failed' then 'failed'
        when p_event_type = 'checkout.session.expired' then 'expired'
        when p_event_type = 'checkout.session.async_payment_succeeded' then 'paid'
        when p_event_type = 'checkout.session.completed' and p_payment_status = 'paid' then 'paid'
        when p_event_type = 'checkout.session.completed' then 'processing'
        else null
    end;

    next_request_status := case
        when next_payment_status = 'paid' then 'paid'
        when next_payment_status = 'processing' then 'processing'
        when next_payment_status in ('failed', 'expired') then 'failed'
        else null
    end;

    if next_payment_status is null or p_session_id is null then
        perform public.resolve_stripe_webhook_failure(p_event_id);
        return true;
    end if;

    update public.payments
    set
        status = next_payment_status,
        stripe_payment_intent_id = coalesce(
            p_payment_intent_id,
            stripe_payment_intent_id
        ),
        customer_email = coalesce(p_customer_email, customer_email),
        paid_at = case
            when next_payment_status = 'paid' then coalesce(paid_at, now())
            else paid_at
        end,
        updated_at = now()
    where stripe_checkout_session_id = p_session_id
    returning payment_request_id into linked_request_id;

    if not found then
        raise exception 'Payment for Stripe Checkout Session % was not found.', p_session_id;
    end if;

    if linked_request_id is not null and next_request_status is not null then
        perform public.transition_payment_request_status(
            linked_request_id,
            next_request_status,
            null,
            jsonb_build_object(
                'stripe_event_id', p_event_id,
                'stripe_event_type', p_event_type
            )
        );
    end if;

    perform public.resolve_stripe_webhook_failure(p_event_id);
    return true;
end;
$$;

create or replace function public.process_stripe_refund_webhook(
    p_event_id text,
    p_event_type text,
    p_stripe_refund_id text,
    p_refund_reference uuid,
    p_payment_intent_id text,
    p_amount bigint,
    p_currency text,
    p_status text,
    p_failure_reason text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
    inserted_count integer;
    refund_record public.payment_refunds%rowtype;
    payment_record public.payments%rowtype;
begin
    insert into public.stripe_webhook_events (
        event_id,
        type,
        processed_at,
        created_at,
        updated_at
    ) values (p_event_id, p_event_type, now(), now(), now())
    on conflict (event_id) do nothing;

    get diagnostics inserted_count = row_count;

    if inserted_count = 0 then
        perform public.resolve_stripe_webhook_failure(p_event_id, 'duplicate_already_processed');
        return false;
    end if;

    select *
    into refund_record
    from public.payment_refunds as refund
    where refund.stripe_refund_id = p_stripe_refund_id
       or (p_refund_reference is not null and refund.reference = p_refund_reference)
    limit 1
    for update;

    if refund_record.id is null then
        select *
        into payment_record
        from public.payments as payment
        where payment.stripe_payment_intent_id = p_payment_intent_id
        for update;

        if payment_record.id is null or payment_record.payment_request_id is null then
            raise exception 'Payment for Stripe PaymentIntent % was not found.',
                p_payment_intent_id;
        end if;

        insert into public.payment_refunds (
            organization_id,
            payment_id,
            payment_request_id,
            reference,
            stripe_refund_id,
            amount,
            currency,
            status,
            reason
        ) values (
            payment_record.organization_id,
            payment_record.id,
            payment_record.payment_request_id,
            coalesce(p_refund_reference, gen_random_uuid()),
            p_stripe_refund_id,
            p_amount,
            lower(p_currency),
            'pending',
            'external_stripe_refund'
        ) returning * into refund_record;
    end if;

    perform public.apply_payment_refund_status(
        refund_record.reference,
        p_stripe_refund_id,
        p_status,
        p_failure_reason,
        null
    );

    perform public.resolve_stripe_webhook_failure(p_event_id);
    return true;
end;
$$;

create or replace function public.prepare_payment_reconciliation(
    p_payment_request_id uuid,
    p_user_id uuid
)
returns table (
    payment_reference uuid,
    organization_id uuid,
    payment_request_id uuid,
    stripe_checkout_session_id text,
    stripe_payment_intent_id text
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    payment_record public.payments%rowtype;
begin
    select payment.*
    into payment_record
    from public.payments as payment
    where payment.payment_request_id = p_payment_request_id;

    if payment_record.id is null then
        raise exception 'Payment was not found.' using errcode = 'P0002';
    end if;

    if not exists (
        select 1
        from public.organization_memberships as membership
        where membership.organization_id = payment_record.organization_id
          and membership.user_id = p_user_id
          and membership.status = 'active'
          and membership.role in ('owner', 'admin', 'accountant')
    ) then
        raise exception 'You are not allowed to reconcile this payment.'
            using errcode = '42501';
    end if;

    if payment_record.stripe_checkout_session_id is null then
        raise exception 'This payment does not have a Stripe Checkout Session.'
            using errcode = '55000';
    end if;

    return query
    select
        payment_record.reference,
        payment_record.organization_id,
        p_payment_request_id,
        payment_record.stripe_checkout_session_id,
        payment_record.stripe_payment_intent_id;
