    add column if not exists refunded_amount bigint not null default 0,
    add column if not exists refunded_at timestamptz;

alter table public.payment_requests
    drop constraint if exists payment_requests_status,
    drop constraint if exists payment_requests_approval_fields,
    drop constraint if exists payment_requests_refunded_amount_range;

alter table public.payment_requests
    add constraint payment_requests_status check (
        status in (
            'draft',
            'submitted',
            'approved',
            'checkout_created',
            'processing',
            'paid',
            'failed',
            'canceled',
            'partially_refunded',
            'refunded'
        )
    ),
    add constraint payment_requests_approval_fields check (
        status not in (
            'approved',
            'checkout_created',
            'processing',
            'paid',
            'failed',
            'partially_refunded',
            'refunded'
        )
        or (approved_by is not null and approved_at is not null)
    ),
    add constraint payment_requests_refunded_amount_range check (
        refunded_amount between 0 and net_amount
    );

create table if not exists public.payment_refunds (
    id bigint generated by default as identity primary key,
    organization_id uuid not null references public.organizations(id) on delete restrict,
    payment_id bigint not null references public.payments(id) on delete restrict,
    payment_request_id uuid not null references public.payment_requests(id) on delete restrict,
    reference uuid not null default gen_random_uuid() unique,
    stripe_refund_id text unique,
    amount bigint not null,
    currency varchar(3) not null,
    status varchar(24) not null default 'pending',
    reason text not null default 'requested_by_customer',
    requested_by uuid references auth.users(id) on delete set null,
    failure_reason text,
    completed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint payment_refunds_positive_amount check (amount > 0),
    constraint payment_refunds_currency_format check (currency ~ '^[a-z]{3}$'),
    constraint payment_refunds_status check (
        status in ('pending', 'requires_action', 'succeeded', 'failed', 'canceled')
    )
);

