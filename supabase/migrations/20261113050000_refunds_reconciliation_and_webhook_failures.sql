create or replace function public.transition_payment_request_status(
    p_payment_request_id uuid,
    p_next_status text,
    p_actor_user_id uuid default null,
    p_metadata jsonb default '{}'::jsonb
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
    current_status text;
    request_organization_id uuid;
begin
    select payment_request.status, payment_request.organization_id
    into current_status, request_organization_id
    from public.payment_requests as payment_request
    where payment_request.id = p_payment_request_id
    for update;

    if not found then
        return false;
    end if;

    if current_status = p_next_status then
        return true;
    end if;

    if not (
        (current_status = 'approved' and p_next_status = 'checkout_created')
        or (current_status = 'failed' and p_next_status in ('checkout_created', 'paid'))
        or (
            current_status = 'checkout_created'
            and p_next_status in ('processing', 'paid', 'failed', 'canceled')
        )
        or (current_status = 'processing' and p_next_status in ('paid', 'failed'))
        or (
            current_status = 'paid'
            and p_next_status in ('partially_refunded', 'refunded')
        )
        or (current_status = 'partially_refunded' and p_next_status = 'refunded')
    ) then
        raise exception 'Invalid payment request transition from % to %.',
            current_status,
            p_next_status
            using errcode = '55000';
    end if;

    update public.payment_requests
    set
        status = p_next_status,
        checkout_started_at = case
            when p_next_status = 'checkout_created' then now()
            else checkout_started_at
        end,
        paid_at = case
            when p_next_status = 'paid' then coalesce(paid_at, now())
            else paid_at
        end,
        failed_at = case
            when p_next_status = 'failed' then now()
            when p_next_status in ('checkout_created', 'paid') then null
            else failed_at
        end,
        refunded_at = case
            when p_next_status = 'refunded' then coalesce(refunded_at, now())
            else refunded_at
        end
    where id = p_payment_request_id;

    insert into public.audit_events (
        organization_id,
        actor_user_id,
        action,
        entity_type,
        entity_id,
        metadata
    ) values (
        request_organization_id,
        p_actor_user_id,
        'payment_request.' || p_next_status,
        'payment_request',
        p_payment_request_id,
        coalesce(p_metadata, '{}'::jsonb)
    );

    return true;
end;
$$;

create or replace function public.prepare_payment_refund(
    p_payment_request_id uuid,
    p_user_id uuid,
    p_reference uuid
)
returns table (
    refund_reference uuid,
    organization_id uuid,
    payment_request_id uuid,
    payment_reference uuid,
    stripe_payment_intent_id text,
    stripe_refund_id text,
    amount bigint,
    currency text,
    refund_status text
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    request_record public.payment_requests%rowtype;
    payment_record public.payments%rowtype;
    refund_record public.payment_refunds%rowtype;
    remaining_amount bigint;
begin
    if p_user_id is null then
        raise exception 'Authentication is required.' using errcode = '28000';
    end if;

    select *
    into request_record
    from public.payment_requests as payment_request
    where payment_request.id = p_payment_request_id
    for update;

    if not found then
        raise exception 'Payment request was not found.' using errcode = 'P0002';
    end if;

    if not exists (
        select 1
        from public.organization_memberships as membership
        where membership.organization_id = request_record.organization_id
          and membership.user_id = p_user_id
          and membership.status = 'active'
          and membership.role in ('owner', 'accountant')
    ) then
        raise exception 'You are not allowed to refund this payment.'
            using errcode = '42501';
    end if;

    select *
    into payment_record
    from public.payments as payment
    where payment.payment_request_id = p_payment_request_id
    for update;

    if payment_record.id is null
       or payment_record.stripe_payment_intent_id is null
       or payment_record.status not in ('paid', 'partially_refunded') then
        raise exception 'Only a settled Stripe payment can be refunded.'
            using errcode = '55000';
    end if;

    remaining_amount := payment_record.amount_total - payment_record.amount_refunded;

    if remaining_amount <= 0 then
        raise exception 'This payment is already fully refunded.'
            using errcode = '55000';
    end if;

    select *
    into refund_record
    from public.payment_refunds as refund
    where refund.payment_id = payment_record.id
      and refund.status in ('pending', 'requires_action')
    order by refund.created_at desc
    limit 1
    for update;

    if refund_record.id is null then
        insert into public.payment_refunds (
            organization_id,
            payment_id,
            payment_request_id,
            reference,
            amount,
            currency,
            requested_by
        ) values (
            request_record.organization_id,
            payment_record.id,
            p_payment_request_id,
            p_reference,
            remaining_amount,
            payment_record.currency,
            p_user_id
        ) returning * into refund_record;

        insert into public.audit_events (
            organization_id,
            actor_user_id,
            action,
            entity_type,
            entity_id,
            metadata
        ) values (
            request_record.organization_id,
            p_user_id,
            'refund.requested',
            'payment_request',
            p_payment_request_id,
            jsonb_build_object(
                'refund_reference', refund_record.reference,
                'amount', refund_record.amount,
                'currency', refund_record.currency
            )
        );
    end if;

    return query
    select
        refund_record.reference,
        request_record.organization_id,
        p_payment_request_id,
        payment_record.reference,
        payment_record.stripe_payment_intent_id,
        refund_record.stripe_refund_id,
        refund_record.amount,
        refund_record.currency::text,
        refund_record.status::text;
end;
$$;

create or replace function public.apply_payment_refund_status(
    p_refund_reference uuid,
    p_stripe_refund_id text,
    p_status text,
    p_failure_reason text default null,
    p_actor_user_id uuid default null
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
    refund_record public.payment_refunds%rowtype;
    previous_status text;
    total_refunded bigint;
    payment_total bigint;
    next_status text;
begin
    if p_status not in ('pending', 'requires_action', 'succeeded', 'failed', 'canceled') then
        raise exception 'Unsupported Stripe refund status %.', p_status
            using errcode = '22023';
    end if;

    select *
    into refund_record
    from public.payment_refunds as refund
    where refund.reference = p_refund_reference
    for update;

    if not found then
        return false;
    end if;

    previous_status := refund_record.status;

    if previous_status in ('succeeded', 'failed', 'canceled')
       and previous_status is distinct from p_status then
        return true;
    end if;

    update public.payment_refunds
    set
        stripe_refund_id = coalesce(p_stripe_refund_id, stripe_refund_id),
        status = p_status,
        failure_reason = p_failure_reason,
        completed_at = case
            when p_status in ('succeeded', 'failed', 'canceled')
                then coalesce(completed_at, now())
            else completed_at
        end,
        updated_at = now()
    where id = refund_record.id;

    if p_status = 'succeeded' then
        select
            coalesce(sum(refund.amount), 0),
            payment.amount_total
        into total_refunded, payment_total
        from public.payment_refunds as refund
        join public.payments as payment on payment.id = refund_record.payment_id
        where refund.payment_id = refund_record.payment_id
          and refund.status = 'succeeded'
        group by payment.amount_total;

        total_refunded := least(coalesce(total_refunded, 0), payment_total);
        next_status := case
            when total_refunded >= payment_total then 'refunded'
            else 'partially_refunded'
        end;

        update public.payments
        set
            amount_refunded = total_refunded,
            status = next_status,
            refunded_at = case
                when next_status = 'refunded' then coalesce(refunded_at, now())
                else refunded_at
            end,
            updated_at = now()
        where id = refund_record.payment_id;

        update public.payment_requests
        set refunded_amount = total_refunded
        where id = refund_record.payment_request_id;

        perform public.transition_payment_request_status(
            refund_record.payment_request_id,
            next_status,
            p_actor_user_id,
            jsonb_build_object(
                'refund_reference', p_refund_reference,
                'stripe_refund_id', p_stripe_refund_id,
                'amount_refunded', total_refunded
            )
        );
    end if;

    if previous_status is distinct from p_status then
        insert into public.audit_events (
            organization_id,
            actor_user_id,
            action,
            entity_type,
            entity_id,
            metadata
        ) values (
            refund_record.organization_id,
            p_actor_user_id,
            'refund.' || p_status,
            'payment_request',
            refund_record.payment_request_id,
            jsonb_build_object(
                'refund_reference', p_refund_reference,
                'stripe_refund_id', p_stripe_refund_id,
                'amount', refund_record.amount,
                'failure_reason', p_failure_reason
            )
        );
    end if;

    return true;
end;
$$;

create or replace function public.record_stripe_webhook_failure(
    p_event_id text,
    p_event_type text,
    p_object_id text,
    p_error_code text,
    p_error_message text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
    tenant_id uuid;
begin
    select payment.organization_id
    into tenant_id
    from public.payments as payment
    where payment.stripe_checkout_session_id = p_object_id
       or payment.stripe_payment_intent_id = p_object_id
    limit 1;

    if tenant_id is null then
        select refund.organization_id
        into tenant_id
        from public.payment_refunds as refund
        where refund.stripe_refund_id = p_object_id
        limit 1;
    end if;

    insert into public.stripe_webhook_failures (
        organization_id,
        event_id,
        event_type,
        object_id,
        error_code,
        error_message
    ) values (
        tenant_id,
        p_event_id,
        p_event_type,
        p_object_id,
        nullif(left(p_error_code, 120), ''),
        left(coalesce(nullif(p_error_message, ''), 'Unknown processing error.'), 1000)
    )
    on conflict (event_id) do update
    set
        organization_id = coalesce(
            public.stripe_webhook_failures.organization_id,
            excluded.organization_id
        ),
        object_id = coalesce(excluded.object_id, public.stripe_webhook_failures.object_id),
        error_code = excluded.error_code,
        error_message = excluded.error_message,
        attempts = public.stripe_webhook_failures.attempts + 1,
        last_failed_at = now(),
        resolved_at = null,
        resolution = null;

    return true;
end;
$$;

create or replace function public.resolve_stripe_webhook_failure(
    p_event_id text,
    p_resolution text default 'processed_on_retry'
)
