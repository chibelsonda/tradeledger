create or replace function public.reconcile_stripe_payment(
    p_payment_request_id uuid,
    p_user_id uuid,
    p_session_status text,
    p_payment_status text,
    p_payment_intent_id text,
    p_refunds jsonb default '[]'::jsonb
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
    payment_record public.payments%rowtype;
    request_record public.payment_requests%rowtype;
    refund_item jsonb;
    reconciled_refunded bigint;
    next_status text;
    next_request_status text;
begin
    select payment.*
    into payment_record
    from public.payments as payment
    where payment.payment_request_id = p_payment_request_id
    for update;

    if payment_record.id is null then
        raise exception 'Payment was not found.' using errcode = 'P0002';
    end if;

    if not exists (
        select 1
        from public.organization_memberships as membership
        where membership.organization_id = payment_record.organization_id
          and membership.user_id = p_user_id
          and membership.status = 'active'
          and membership.role in ('owner', 'admin', 'accountant')
    ) then
        raise exception 'You are not allowed to reconcile this payment.'
            using errcode = '42501';
    end if;

    for refund_item in
        select value from jsonb_array_elements(coalesce(p_refunds, '[]'::jsonb))
    loop
        if nullif(refund_item ->> 'id', '') is null
           or coalesce((refund_item ->> 'amount')::bigint, 0) <= 0 then
            continue;
        end if;

        insert into public.payment_refunds (
            organization_id,
            payment_id,
            payment_request_id,
            stripe_refund_id,
            amount,
            currency,
            status,
            reason,
            failure_reason,
            completed_at
        ) values (
            payment_record.organization_id,
            payment_record.id,
            p_payment_request_id,
            refund_item ->> 'id',
            (refund_item ->> 'amount')::bigint,
            lower(refund_item ->> 'currency'),
            refund_item ->> 'status',
            coalesce(nullif(refund_item ->> 'reason', ''), 'external_stripe_refund'),
            nullif(refund_item ->> 'failure_reason', ''),
            case
                when refund_item ->> 'status' in ('succeeded', 'failed', 'canceled')
                    then now()
                else null
            end
        )
        on conflict (stripe_refund_id) do update
        set
            status = excluded.status,
            failure_reason = excluded.failure_reason,
            completed_at = coalesce(
                public.payment_refunds.completed_at,
                excluded.completed_at
            ),
            updated_at = now();
    end loop;

    select coalesce(sum(refund.amount), 0)
    into reconciled_refunded
    from public.payment_refunds as refund
    where refund.payment_id = payment_record.id
      and refund.status = 'succeeded';

    reconciled_refunded := least(reconciled_refunded, payment_record.amount_total);

    select *
    into request_record
    from public.payment_requests as payment_request
    where payment_request.id = p_payment_request_id
    for update;

    next_status := case
        when reconciled_refunded >= payment_record.amount_total then 'refunded'
        when reconciled_refunded > 0 then 'partially_refunded'
        when p_payment_status = 'paid' then 'paid'
        when p_session_status = 'complete' then 'processing'
        when p_session_status = 'expired' then 'expired'
        else payment_record.status
    end;

    next_request_status := case
        when next_status in ('paid', 'partially_refunded', 'refunded') then next_status
        when next_status in ('failed', 'expired') then 'failed'
        when next_status = 'processing' then 'processing'
        else request_record.status
    end;

    update public.payments
    set
        status = next_status,
        stripe_payment_intent_id = coalesce(
            p_payment_intent_id,
            stripe_payment_intent_id
        ),
        amount_refunded = reconciled_refunded,
        paid_at = case
            when next_status in ('paid', 'partially_refunded', 'refunded')
                then coalesce(paid_at, now())
            else paid_at
        end,
        refunded_at = case
            when next_status = 'refunded' then coalesce(refunded_at, now())
            else refunded_at
        end,
        updated_at = now()
    where id = payment_record.id;

    update public.payment_requests
    set refunded_amount = reconciled_refunded
    where id = p_payment_request_id;

    if request_record.status is distinct from next_request_status then
        perform public.transition_payment_request_status(
            p_payment_request_id,
            next_request_status,
            p_user_id,
            jsonb_build_object('source', 'stripe_reconciliation')
        );
    end if;

    insert into public.audit_events (
        organization_id,
        actor_user_id,
        action,
        entity_type,
        entity_id,
        metadata
    ) values (
        payment_record.organization_id,
        p_user_id,
        'payment.reconciled',
        'payment_request',
        p_payment_request_id,
        jsonb_build_object(
            'stripe_session_status', p_session_status,
            'stripe_payment_status', p_payment_status,
            'amount_refunded', reconciled_refunded,
            'resulting_status', next_status
        )
    );

    return next_status;
end;
$$;

